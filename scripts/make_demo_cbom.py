def build() -> dict:
    comps = []
    for ident, name, prim, pset, curve, funcs, usage, exposure, shelf, mig, where in ASSETS:
        alg: dict = {"primitive": prim, "cryptoFunctions": funcs}
        if pset:
            alg["parameterSetIdentifier"] = pset
        if curve:
            alg["curve"] = curve
        comps.append(
            {
                "type": "cryptographic-asset",
                "bom-ref": ident,
                "name": name,
                "description": where,
                "cryptoProperties": {"assetType": "algorithm", "algorithmProperties": alg},
                "properties": [
                    {"name": "qday:shelf_life_years", "value": str(shelf)},
                    {"name": "qday:migration_years", "value": str(mig)},
                    {"name": "qday:exposure", "value": exposure},
                    {"name": "qday:usage", "value": usage},
                ],
            }
        )
    return {
        "bomFormat": "CycloneDX",
        "specVersion": "1.6",
        "serialNumber": "urn:uuid:6f1d1c0a-2b7e-4d5f-9a39-0c4b8e7d1a52",
        "version": 1,
        "metadata": {
            "timestamp": "2026-11-08T00:00:00Z",
            "properties": [
                {"name": "qday:fictional", "value": "true"},
                {"name": "qday:company", "value": "Examplia Pay (fictional fintech)"},
            ],
        },
        "components": comps,
    }


def main() -> int:
    text = json.dumps(build(), indent=2) + "\n"
    err = JsonStrictValidator(SchemaVersion.V1_6).validate_str(text)
    if err is not None:
        print("INVALID:", err)
        return 1
    if json.loads(dump_cbom(parse_cbom(text))) != json.loads(text):
        print("round trip changed the document")
        return 1
    OUT.write_text(text)
    print(f"wrote {OUT} with {len(ASSETS)} assets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
