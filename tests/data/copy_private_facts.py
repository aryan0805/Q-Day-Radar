"""Copies, once, the few facts that tests and audits used to read from the dev repo's own notes.

Those notes are not part of the public repo, so a test must not open them. This script reads the
two note files whose paths you pass on the command line, prints every source line it uses, and
writes `tests/data/private_facts.json`. Run it only in the dev repo, only when a fact must be
added; the JSON is then the record. The line hashes let anyone with the dev repo check a copy.

    uv run python tests/data/copy_private_facts.py <event-log-file> <decision-record-file>

Facts copied:
- the three events that show the physical-v2 parameters were pre-registered before the first
  calibration was reported (type, minute stamp, author, hash of the source line);
- which cross-check case ids have a written explanation (cases whose ratio exceeds 3x must).
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "tests" / "data" / "private_facts.json"
CROSSCHECK = ROOT / "results" / "estimate" / "crosscheck.json"

EVENTS = {
    "interface": lambda ln: "[INTERFACE]" in ln and "physical v2" in ln.lower(),
    "decision": lambda ln: "[DECISION]" in ln and "v2 pre-registration accepted" in ln,
    "first_calibration": lambda ln: "[READY_FOR_TEST]" in ln and "physical_v2" in ln,
}
LINE = re.compile(r"^- (\d{4}-\d\d-\d\d \d\d:\d\d) · (\w+) · \[(\w+)\]")


def main(log_path: str, decisions_path: str) -> None:
    log = Path(log_path).read_text().splitlines()
    events = {}
    for name, pred in EVENTS.items():
        n, line = next((i, ln) for i, ln in enumerate(log, 1) if pred(ln))
        m = LINE.match(line)
        assert m, f"unparsable event line {n}"
        print(f"event {name}: line {n}: {line[:160]}")
        events[name] = {
            "time": m.group(1),
            "author": m.group(2),
            "type": m.group(3),
            "line_sha256": hashlib.sha256(line.encode()).hexdigest(),
        }
    decisions = Path(decisions_path).read_text().splitlines()
    cases = [r["case"] for r in json.loads(CROSSCHECK.read_text())["cases"]]
    explained = []
    for case in cases:
        hits = [ln for ln in decisions if case in ln]
        if hits:
            explained.append(case)
            print(f"explained {case}: {len(hits)} line(s); first: {hits[0][:110]}")
    print(f"{len(explained)} of {len(cases)} cross-check case ids have a written explanation")
    OUT.write_text(
        json.dumps(
            {
                "note": "copied once by tests/data/copy_private_facts.py; read by tests, never "
                "regenerated by a test",
                "preregistration_events": events,
                "explained_crosscheck_case_ids": explained,
            },
            indent=1,
        )
        + "\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
